-- 7. HOW TRACKING GETS POPULATED ───────────────────────────────
--
-- There is no carrier integration. When an order actually ships, the
-- owner sets the tracking fields (and the fulfillment status) directly,
-- e.g.:
--
--   update public.orders
--      set fulfillment_status = 'shipped',
--          shipped_at         = now(),
--          shipping_carrier   = 'DHL',          -- or NULL if unknown
--          tracking_number    = '00340434161094042557',
--          tracking_url       = 'https://...'   -- or NULL if there is none
--    where order_number = 'GLOA-2026-000123';
--
-- Leave any field NULL rather than filling it with a guess: the customer
-- UI renders a bare tracking number perfectly well without a carrier,
-- and shows no link at all rather than a fabricated one.
--
-- 'delivered' is deliberately never set automatically anywhere in this
-- codebase. Set fulfillment_status = 'delivered' only if there is a real
-- delivery confirmation; otherwise 'shipped' remains the honest state.
